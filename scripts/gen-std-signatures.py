#!/usr/bin/env python3
"""Regenerate spec/std-signatures.md from the canonical lmcode std schema.

Usage:
    python3 scripts/gen-std-signatures.py SCHEMA [--docs DOCS] [--check] [--output FILE]

SCHEMA is a lmcode std schema document (canonical source:
lmcode-cpp/std/lmcode-std.schema.json; byte-identical copies are pinned by
std.lock in every SDK and bundled into the compiler). With --docs, the
companion lmcode-std.docs.json supplies the area/summary/errors columns; the
docs' signature set must equal the schema's exactly, or the run fails.

Without --check the output file is rewritten (default: spec/std-signatures.md
next to this script's repository root). With --check nothing is written; the
exit code is 0 when the committed file matches what regeneration would
produce and 1 (with a diff on stderr) otherwise, so drift is visible in CI.
"""
import argparse
import difflib
import hashlib
import json
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = REPO_ROOT / "spec" / "std-signatures.md"
AREA_ORDER = ["file", "math", "string", "encoding", "json", "collections", "containers"]


def fail(message):
    print("gen-std-signatures: " + message, file=sys.stderr)
    raise SystemExit(2)


def signatures(schema):
    """Canonical `fn NAME(T1, T2) -> R` / `method Type.name(T1) -> R` lines, sorted."""
    out = []
    for name, overloads in (schema.get("functions") or {}).items():
        for decl in overloads:
            out.append("fn %s(%s) -> %s" % (name, ", ".join(decl_params(decl)), decl_returns(decl)))
    for type_name, spec in (schema.get("types") or {}).items():
        for method, overloads in (spec.get("methods") or {}).items():
            for decl in overloads:
                returns = decl_returns(decl)
                out.append("method %s.%s(%s) -> %s"
                           % (type_name, method, ", ".join(decl_params(decl)),
                              type_name if returns == "self" else returns))
    return sorted(out)


def decl_params(decl):
    params = decl.get("params")
    if not isinstance(params, list) or not all(isinstance(p, str) for p in params):
        fail('a declaration\'s "params" must be a list of type names')
    return params


def decl_returns(decl):
    returns = decl.get("returns")
    return "void" if returns is None else returns


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(schema, schema_bytes, docs, docs_bytes):
    lines = signatures(schema)
    if docs is not None:
        documented = docs.get("signatures") or {}
        if sorted(documented) != lines:
            missing = sorted(set(lines) - set(documented))
            extra = sorted(set(documented) - set(lines))
            fail("docs signature set differs from the schema"
                 + ("; undocumented: " + ", ".join(missing[:5]) if missing else "")
                 + ("; not in the schema: " + ", ".join(extra[:5]) if extra else ""))
        if docs.get("version") is not None and "lmcode_std_v%s" % docs["version"] != schema.get("name"):
            fail("docs version %s does not match schema name %s" % (docs["version"], schema.get("name")))

    sha = hashlib.sha256(schema_bytes).hexdigest()
    header = [
        "# lmcode std — canonical signature list",
        "",
        "Generated by `scripts/gen-std-signatures.py` from the canonical schema; do not edit by hand.",
        "Regenerate (paths are this machine's checkouts; any byte-identical copy works):",
        "",
        "```sh",
        "python3 scripts/gen-std-signatures.py /path/to/lmcode-cpp/std/lmcode-std.schema.json \\",
        "    --docs /path/to/lmcode-cpp/std/lmcode-std.docs.json",
        "```",
        "",
        "`--check` instead compares the committed file with a fresh generation and exits 1 on drift.",
        "",
        "Schema `%s`, %d signatures, SHA-256 of the exact schema bytes `%s`."
        % (schema.get("name"), len(lines), sha),
    ]
    if docs is not None:
        header.append("Metadata from the companion docs file (SHA-256 `%s`)."
                      % hashlib.sha256(docs_bytes).hexdigest())
    header.append("")

    if docs is None:
        return "\n".join(header + ["", "| Signature |", "| --- |"]
                         + ["| `%s` |" % cell(s) for s in lines]) + "\n"

    grouped = {}
    for line in lines:
        grouped.setdefault(documented[line].get("area", "other"), []).append(line)
    order = [a for a in AREA_ORDER if a in grouped] + sorted(a for a in grouped if a not in AREA_ORDER)
    parts = ["\n".join(header)]
    for area in order:
        rows = ["## %s (%d)" % (area, len(grouped[area])), "",
                "| Signature | Summary | Errors |", "| --- | --- | --- |"]
        for line in grouped[area]:
            meta = documented[line]
            errors = meta.get("errors") or []
            rows.append("| `%s` | %s | %s |" % (cell(line), cell(meta.get("summary", "")),
                                                  cell("; ".join(errors) if errors else "—")))
        parts.append("\n".join(rows))
    return "\n\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("schema", help="lmcode-std.schema.json")
    parser.add_argument("--docs", help="lmcode-std.docs.json (adds area/summary/errors columns)")
    parser.add_argument("--check", action="store_true", help="compare with the output file; write nothing")
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    args = parser.parse_args()

    schema_bytes = pathlib.Path(args.schema).read_bytes()
    try:
        schema = json.loads(schema_bytes)
    except ValueError as error:
        fail("%s is not valid JSON: %s" % (args.schema, error))
    if not isinstance(schema, dict) or schema.get("dsl.schema") != 2:
        fail('%s is not a dsl.schema 2 document' % args.schema)
    docs = docs_bytes = None
    if args.docs:
        docs_bytes = pathlib.Path(args.docs).read_bytes()
        docs = json.loads(docs_bytes)

    text = render(schema, schema_bytes, docs, docs_bytes)
    if args.check:
        current = pathlib.Path(args.output).read_text() if pathlib.Path(args.output).exists() else None
        if current == text:
            print("%s is up to date" % args.output)
            return
        if current is None:
            print("%s does not exist" % args.output, file=sys.stderr)
        else:
            sys.stderr.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True),
                                                       args.output, "regenerated"))
        raise SystemExit(1)
    pathlib.Path(args.output).write_text(text)
    print("wrote %s (%d signatures)" % (args.output, text.count("\n| `")))


if __name__ == "__main__":
    main()
